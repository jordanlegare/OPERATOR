CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE IF NOT EXISTS operator_journal_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id TEXT NOT NULL UNIQUE,
    event_id TEXT,
    occurred_at TIMESTAMPTZ NOT NULL,
    kind TEXT NOT NULL,
    body TEXT NOT NULL,
    conversation_id TEXT,
    session_id TEXT,
    related_session_id TEXT,
    turn_id TEXT,
    tool_call_id TEXT,
    iteration INTEGER,
    payload JSONB NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS operator_journal_event_id_unique
    ON operator_journal_entries (event_id)
    WHERE event_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS operator_journal_occurred_at_idx
    ON operator_journal_entries (occurred_at, id);

CREATE INDEX IF NOT EXISTS operator_journal_conversation_idx
    ON operator_journal_entries (conversation_id, id)
    WHERE conversation_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS operator_journal_search_documents (
    document_key TEXT PRIMARY KEY,
    record_id TEXT NOT NULL,
    entry_id BIGINT NOT NULL REFERENCES operator_journal_entries(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    body TEXT NOT NULL,
    search_vector TSVECTOR GENERATED ALWAYS AS (to_tsvector('simple', body)) STORED
);

CREATE INDEX IF NOT EXISTS operator_journal_search_fts_idx
    ON operator_journal_search_documents USING GIN (search_vector);

CREATE INDEX IF NOT EXISTS operator_journal_search_trgm_idx
    ON operator_journal_search_documents USING GIN (lower(body) gin_trgm_ops);

CREATE INDEX IF NOT EXISTS operator_journal_search_entry_idx
    ON operator_journal_search_documents (entry_id);

-- Supports loading a full historical search result by its stable record ID.
CREATE INDEX IF NOT EXISTS operator_journal_search_record_idx
    ON operator_journal_search_documents (record_id);

